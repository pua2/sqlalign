def style_for(setting: Setting, value):
    """HOUSE with `setting` set to `value`, plus whatever else the setting needs
    to have any visible effect."""
    overrides = {setting.name: value}
    if setting.name == "select_indent":
        overrides["select_placement"] = "own_line"
    if setting.name == "river_gutter":
        overrides["clause_keyword_align"] = "river"
    return dataclasses.replace(HOUSE, **overrides)


def label(setting: Setting, value) -> str:
    """How a value is written in the docs."""
    if setting.kind == "targets":
        if not value:
            return "frozenset()"
        if value == HOUSE.align_targets:
            return "the default set"
        return "{" + ", ".join(sorted(value)) + "}"
    if isinstance(value, Width):
        return f"{value.width}" if value.width else "0 (off)"
    return repr(value)


def field_type(name: str) -> str:
    for f in dataclasses.fields(Style):
        if f.name == name:
            t = f.type if isinstance(f.type, str) else getattr(f.type, "__name__", str(f.type))
            return {"bool": "bool", "int": "int", "str": "str",
                    "frozenset[str]": "set of str",
                    "int | None": "int or unset"}.get(t, t)
    raise KeyError(name)
