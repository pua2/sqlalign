"""The per-setting reference data, and the SQL that demonstrates each one.

Every example on the configuration page is GENERATED by running the formatter,
never written by hand -- the same rule the guide's console transcripts follow.
A hand-written example is a claim about the tool; a generated one is the tool.

Each entry carries the SQL that actually exercises its knob. A shared sample
would leave most settings showing two identical panels: `on_placement` needs a
join, `river_gutter` needs a river, `body_blank_lines` needs a `$$` body. The
sample is the part that cannot be derived, so it is the part written down here.
"""
